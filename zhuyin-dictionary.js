// AAC 常用候選補強：當完整音節尚未有專屬候選時，
// 仍可由相同開頭的既有候選彙整，避免畫面完全空白。
function normalizeZhuyinKey(k) {
  return k.endsWith('ˉ') ? k.slice(0,-1) : k;
}
function isKnownBaseSyllable(k) {
  return ZHUYIN_BASE_SYLLABLES.includes(normalizeZhuyinKey(k).replace(/[ˊˇˋ˙]$/,''));
}
function zhuyinCandidates(input) {
  if(!input) return [];
  const raw=input;
  const lookup=normalizeZhuyinKey(raw);
  const noTone=lookup.replace(/[ˊˇˋ˙]$/,'');
  let result=[...(dict[raw]||[]), ...(dict[lookup]||[])];

  // If exact tone key is absent, use the base syllable as a graceful fallback.
  if(!result.length && /[ˉˊˇˋ˙]$/.test(raw)) result.push(...(dict[noTone]||[]));

  // Partial composition: aggregate all matching candidate groups.
  if(!result.length) {
    for(const [k,v] of Object.entries(dict)) {
      const nk=normalizeZhuyinKey(k).replace(/[ˊˇˋ˙]$/,'');
      if(nk.startsWith(noTone)) result.push(...v);
    }
  }
  return [...new Set(result)].slice(0,18);
}
